-- Apply in the SQL editor of the portfolio Supabase project, after portfolio_content.sql.
-- The shop: products edited in the CMS (/analytics/content/products), orders paid through PayMongo,
-- and private product files. Same access model as every other table: only the server-side secret key
-- reads or writes; there are no public RLS policies.

create table if not exists public.products (
  id integer generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  kind text not null default 'digital' check (kind in ('digital', 'guide', 'service')),
  title text not null,
  summary text not null default '',
  body text,
  -- Whole pesos. PayMongo is charged in centavos (price_php * 100) at checkout.
  price_php integer not null check (price_php >= 20),
  cover_image text,
  -- Path inside the private shop-files bucket. Digital products and guides need one to be sold.
  file_path text,
  -- Shown after payment for services: what happens next, booking link, intake form.
  service_instructions text,
  -- New products are hidden until switched on.
  active boolean not null default false,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  product_id integer not null references public.products (id) on delete restrict,
  -- Copied at checkout so the order keeps what was bought, even if the product is edited later.
  product_title text not null,
  buyer_name text not null check (char_length(buyer_name) between 1 and 120),
  buyer_email text not null check (char_length(buyer_email) between 3 and 254),
  amount integer not null check (amount > 0), -- centavos
  currency text not null default 'PHP',
  status text not null default 'pending' check (status in ('pending', 'paid', 'refunded', 'failed')),
  provider text not null default 'paymongo',
  checkout_session_id text unique,
  payment_id text,
  download_count integer not null default 0,
  receipt_sent_at timestamptz,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);

-- One row per webhook event. The unique id makes retried events a no-op.
create table if not exists public.payment_events (
  event_id text primary key,
  event_type text not null,
  livemode boolean not null,
  received_at timestamptz not null default now(),
  payload jsonb not null
);

-- Counts a download only while the order is paid, under the limit, and inside the download window.
-- Returns false when the download must be refused. Atomic, so parallel requests cannot exceed the limit.
create or replace function public.consume_order_download(p_order_id uuid, p_limit integer, p_days integer)
returns boolean language plpgsql security invoker set search_path = '' as $$
declare
  counted integer;
begin
  update public.orders set download_count = download_count + 1
  where id = p_order_id and status = 'paid' and download_count < p_limit
    and paid_at > now() - make_interval(days => p_days);
  get diagnostics counted = row_count;
  return counted = 1;
end $$;

do $$
declare t text;
begin
  foreach t in array array['products', 'orders', 'payment_events'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to service_role', t);
  end loop;
end $$;
revoke all on sequence public.products_id_seq from anon, authenticated;
grant usage, select on sequence public.products_id_seq to service_role;
revoke all on function public.consume_order_download(uuid, integer, integer) from public, anon, authenticated;
grant execute on function public.consume_order_download(uuid, integer, integer) to service_role;
-- No public RLS policies. The secret key is used only in server-side code.

-- Private bucket for product files (zip, pdf). No storage.objects policy and not public: files are
-- reachable only through short-lived signed links that the download route creates after checking the order.
-- 50 MB per file; upload in Supabase Studio > Storage > shop-files.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('shop-files', 'shop-files', false, 52428800, array['application/zip', 'application/x-zip-compressed', 'application/pdf'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;
