-- Apply in the SQL editor of the dedicated portfolio Supabase project.
-- Portfolio content edited from the admin CMS (/analytics/content). Same access model as the analytics
-- tables: only the server-side secret key reads or writes; there are no public RLS policies.

-- Singleton for page copy that is not a list of records (hero, about, section statements, contact).
create table if not exists public.site_settings (
  id smallint primary key default 1 check (id = 1),
  content jsonb not null,
  updated_at timestamptz not null default now()
);

-- Project ids are stable: analytics counts pop-up opens per id. The identity sequence never reuses an id.
create table if not exists public.projects (
  id integer generated by default as identity primary key,
  title text not null,
  description text not null default '',
  image_url text,
  tech_stack text[] not null default '{}',
  live_url text,
  github_url text,
  featured boolean not null default true,
  role text,
  problem text,
  outcome text,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.timeline_entries (
  id integer generated by default as identity primary key,
  type text not null check (type in ('experience', 'education')),
  organization text not null,
  role text not null,
  description text not null default '',
  start_date text not null,
  end_date text,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.publications (
  id integer generated by default as identity primary key,
  title text not null,
  venue text not null,
  status text not null check (status in ('Published', 'Accepted', 'Under review')),
  doi text,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.ip_items (
  id integer generated by default as identity primary key,
  title text not null,
  detail text not null default '',
  proof_url text,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);
-- Added after the first deploy; keeps existing databases in step with the table above.
alter table public.ip_items add column if not exists proof_url text;

create table if not exists public.capability_groups (
  id integer generated by default as identity primary key,
  title text not null,
  tools text[] not null default '{}',
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['site_settings', 'projects', 'timeline_entries', 'publications', 'ip_items', 'capability_groups'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to service_role', t);
  end loop;
  foreach t in array array['projects', 'timeline_entries', 'publications', 'ip_items', 'capability_groups'] loop
    execute format('revoke all on sequence %s from anon, authenticated', pg_get_serial_sequence('public.' || t, 'id'));
    execute format('grant usage, select on sequence %s to service_role', pg_get_serial_sequence('public.' || t, 'id'));
  end loop;
end $$;
-- No public RLS policies. The secret key is used only in server-side code.

-- Public bucket for CMS images. Files are readable by URL (the Next image optimizer fetches them);
-- there is no storage.objects policy, so only the secret key can upload, replace, list, or delete.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('portfolio-media', 'portfolio-media', true, 4194304, array['image/webp', 'image/jpeg', 'image/png', 'image/avif'])
on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;
